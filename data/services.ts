// Данные об услугах — добавление нового объекта в массив автоматически
// создаёт страницу /services/[slug]/, карточку на главной и пункт в меню.

import type { ServiceType } from '@/lib/validation';

// Ключ иконки — рендерится в ServicesSection.tsx и на странице услуги
export type ServiceIconKey = 'trash' | 'hammer' | 'truck';
export type BadgeIconKey = 'truck' | 'clock' | 'hardhat' | 'mappin' | 'shield';

/** Пункт списка с именем и подписью */
export interface NamedItem {
  name: string;
  desc: string;
}

/** Шаг процесса */
export interface ProcessStep {
  title: string;
  desc: string;
}

/** Строка таблицы цен */
export type TableRow = [string, string];

/** Единица техники (для страницы доставки) */
export interface EquipmentLink {
  name: string;
  weight: string;
  href: string;
}

/**
 * Блок контента для секции деталей на странице услуги.
 * Дискриминированный union — каждый тип рендерится своим шаблоном.
 */
export type DetailBlock =
  | { type: 'checklist'; heading: string; items: string[] }
  | { type: 'grid-cards'; heading: string; items: NamedItem[] }
  | { type: 'steps'; heading: string; items: ProcessStep[] }
  | {
      type: 'zone-table';
      heading: string;
      headers: [string, string];
      rows: TableRow[];
      note?: string;
    }
  | { type: 'equipment-links'; heading: string; items: EquipmentLink[] }
  | { type: 'included'; heading: string; items: string[] };

/** Компоновка секции деталей */
export type DetailSection =
  | { layout: 'single'; block: DetailBlock }
  | { layout: 'two-col'; left: DetailBlock; right: DetailBlock };

/** Блок SEO-текста */
export interface SeoText {
  mainH2: string;
  sections: Array<{ h3?: string; paragraphs: string[] }>;
}

export interface ServiceHero {
  h1Main: string;
  h1Accent: string;
  description: string;
  badge1: { iconKey: BadgeIconKey; value: string; label: string };
  badge2: { iconKey: BadgeIconKey; value: string; label: string };
}

export interface Service {
  slug: string;
  /** Тип для ServiceForm (должен совпадать с ServiceType из lib/validation) */
  serviceType: ServiceType;
  iconKey: ServiceIconKey;
  name: string;
  shortDescription: string;
  priceDisplay: string;
  /** Буллиты для карточки на главной */
  bullets: string[];
  /** Заголовок модального окна на главной */
  modalTitle: string;
  /** Данные для hero-секции страницы */
  hero: ServiceHero;
  /** Секции деталей (что входит, виды работ, процесс, таблицы) */
  detailSections: DetailSection[];
  /** SEO-текст в нижней части страницы */
  seoText: SeoText;
  /** Заголовок и подзаголовок формы */
  formTitle: string;
  formSubtitle: string;
  featured: boolean;
  order: number;
  seo: {
    title: string;
    metaDescription: string;
    ogDescription: string;
  };
}

